/**
 * How a Web Push payload becomes a system notification (ZIG-I21). Shared by the
 * service worker (`src/app/sw.ts`, which bundles it with esbuild) and the
 * server-side payload builder, so this module has no imports and no server or
 * DOM dependencies.
 *
 * Android Chrome uses every option here; Safari ignores `badge`, `actions`,
 * `vibrate` and `renotify`, so iOS keeps showing the plain notification.
 */

export type PushActionId = 'crear' | 'ver' | 'descargar';

export type PushAction = {
  action: PushActionId;
  title: string;
  /** Page (or download) the action opens. */
  url: string;
};

export type PushPayload = {
  title: string;
  body: string | null;
  /** Page to open on tap; the app origin is added by the service worker. */
  url: string | null;
  /** Collapses repeats of the same notification on the device. */
  tag: string;
  /** Notification type (`schedule_overdue`, `export_ready`, …). */
  type: string;
  notificationId: number;
  /** Android shows at most two action buttons. */
  actions: PushAction[];
  /** Unread notifications for the receiving user, for the app icon badge. */
  unread?: number;
};

export const PUSH_ICON_URL = '/icons/icon-192.png';
/** Monochrome silhouette generated by `npm run icons:generate`. */
export const PUSH_BADGE_URL = '/icons/badge-96.png';
export const OVERDUE_VIBRATE_PATTERN = [100, 50, 100];
export const MAX_PUSH_ACTIONS = 2;
export const NOTIFICATION_QUERY_PARAM = 'notification';

/** Options Chrome accepts beyond the DOM lib's `NotificationOptions`. */
export type PushNotificationOptions = NotificationOptions & {
  actions?: Array<{ action: string; title: string }>;
  renotify?: boolean;
  vibrate?: number[];
};

export type PushNotificationData = {
  url: string;
  actions: Partial<Record<PushActionId, string>>;
  notificationId: number | null;
};

/**
 * Add `?notification=<id>` to an in-app path so the page it opens marks the
 * notification read. External URLs (the export download) are left alone.
 */
export const withNotificationParam = (url: string, notificationId: number): string => {
  if (!url.startsWith('/')) return url;
  const [path, hash] = url.split('#', 2);
  const separator = path.includes('?') ? '&' : '?';
  return `${path}${separator}${NOTIFICATION_QUERY_PARAM}=${notificationId}${hash ? `#${hash}` : ''}`;
};

/** Title and options for `registration.showNotification`. */
export const buildNotificationDisplay = (
  payload: Partial<PushPayload>,
): { title: string; options: PushNotificationOptions } => {
  const actions = (payload.actions ?? []).slice(0, MAX_PUSH_ACTIONS);
  // Only overdue services buzz and re-alert when they replace an earlier
  // notification with the same tag; everything else arrives quietly.
  const alert = payload.type === 'schedule_overdue' && Boolean(payload.tag);
  const data: PushNotificationData = {
    url: payload.url ?? '/dashboard',
    actions: Object.fromEntries(actions.map((item) => [item.action, item.url])),
    notificationId: payload.notificationId ?? null,
  };

  return {
    title: payload.title || 'ZigZag',
    options: {
      body: payload.body ?? undefined,
      icon: PUSH_ICON_URL,
      badge: PUSH_BADGE_URL,
      tag: payload.tag,
      data,
      ...(actions.length > 0
        ? { actions: actions.map(({ action, title }) => ({ action, title })) }
        : {}),
      ...(alert ? { vibrate: OVERDUE_VIBRATE_PATTERN, renotify: true } : {}),
    },
  };
};

/** The URL a tap (no action) or an action button opens. */
export const resolveNotificationClickUrl = (
  data: Partial<PushNotificationData> | undefined,
  action: string,
): string => {
  const actionUrl = action ? data?.actions?.[action as PushActionId] : undefined;
  return actionUrl ?? data?.url ?? '/dashboard';
};
