/**
 * Regenerates the base64 font modules the receipt PDF embeds with jsPDF.
 *
 * Source TTFs live in assets/fonts/ibm-plex (IBM Plex, SIL OFL 1.1, from the
 * official IBM/plex GitHub releases @ibm/plex-sans@1.1.0 and @ibm/plex-mono@1.1.0).
 * Each font is subset (harfbuzz through `subset-font`, hinting kept) to the
 * code points in src/lib/pdf-supported-ranges.json, the same list
 * src/lib/pdf-text-support.ts allows (ZIG-I20-4), so the PDF never asks for a
 * glyph the embedded font lacks and the five modules weigh ~0.5 MB instead of
 * ~1.2 MB.
 * Output: src/lib/receipt-pdf/fonts/<family>-<weight>.ts, one exported string each.
 *
 * Usage: npm run pdf-fonts:generate
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const sourceDir = path.join(root, 'assets/fonts/ibm-plex');
const outDir = path.join(root, 'src/lib/receipt-pdf/fonts');
const rangesFile = path.join(root, 'src/lib/pdf-supported-ranges.json');

export const PDF_FONTS = [
  { file: 'IBMPlexSans-Regular.ttf', module: 'plex-sans-400', exportName: 'PLEX_SANS_400' },
  { file: 'IBMPlexSans-Medium.ttf', module: 'plex-sans-500', exportName: 'PLEX_SANS_500' },
  { file: 'IBMPlexSans-SemiBold.ttf', module: 'plex-sans-600', exportName: 'PLEX_SANS_600' },
  { file: 'IBMPlexMono-Regular.ttf', module: 'plex-mono-400', exportName: 'PLEX_MONO_400' },
  { file: 'IBMPlexMono-Medium.ttf', module: 'plex-mono-500', exportName: 'PLEX_MONO_500' },
];

/** Every code point of pdf-supported-ranges.json as one string for the subsetter. */
const subsetText = () => {
  const ranges = JSON.parse(fs.readFileSync(rangesFile, 'utf8'));
  let text = '';
  for (const [start, end] of ranges) {
    for (let code = Number(start); code <= Number(end); code += 1) {
      text += String.fromCodePoint(code);
    }
  }
  return text;
};

fs.mkdirSync(outDir, { recursive: true });
const text = subsetText();

for (const font of PDF_FONTS) {
  const full = fs.readFileSync(path.join(sourceDir, font.file));
  const subset = await subsetFont(full, text, { targetFormat: 'truetype' });
  const base64 = subset.toString('base64');
  const contents = [
    '// Generated by scripts/generate-pdf-fonts.mjs. Do not edit.',
    `// Source: assets/fonts/ibm-plex/${font.file} (SIL OFL 1.1), subset to src/lib/pdf-supported-ranges.json.`,
    `export const ${font.exportName} =`,
    `  '${base64}';`,
    '',
  ].join('\n');
  fs.writeFileSync(path.join(outDir, `${font.module}.ts`), contents);
  console.log(
    `wrote src/lib/receipt-pdf/fonts/${font.module}.ts (${full.length} -> ${subset.length} bytes, ${base64.length} chars)`,
  );
}
